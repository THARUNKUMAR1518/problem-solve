public class funmax {
    static int max (int a,int b){
        if(a<b){
            return b;
        }
        else{
            return a;
        }
        }
    public static void main(String[] args) {
        int a=45;
        int b=65;
        int m=max(a,b);
        System.out.print("The maximum is "+m);
    }}


    
    

